import { strict as assert } from 'node:assert'
import { resolve } from 'node:path'

const root = resolve(process.argv[2] ?? new URL('../..', import.meta.url).pathname)
const { stripToolReferenceBlocksFromUserMessage: strip, stripUnavailableToolReferencesFromUserMessage: available } = await import(`${root}/src/utils/messages/apiView.ts`)
const { STRIPPED_ADMISSION_RECORD_TEXT } = await import(`${root}/src/tools/ToolSearchTool/prompt.ts`)
const ref = (tool_name?: string) => ({ type: 'tool_reference', ...(tool_name === undefined ? {} : { tool_name }) })
const result = (content: unknown, tool_use_id: string) => ({ type: 'tool_result', content, tool_use_id })
const user = (content: unknown) => ({ type: 'user', uuid: 'reference-row', message: { role: 'user', content } })
const keptText = { type: 'text', text: 'retained' }
const empty = result([], 'empty')
const intact = result([keptText], 'intact')
const removed = result([ref('gone')], 'removed')
const plain = { type: 'text', text: 'sibling' }
const row = user([empty, intact, removed, plain])
const all = strip(row)
assert.notEqual(all, row)
assert.notEqual(all.message.content[0], empty)
assert.notEqual(all.message.content[1], intact)
assert.equal(all.message.content[1].content[0], keptText)
assert.equal(all.message.content[3], plain)
assert.deepEqual(all.message.content[0].content, [{ type: 'text', text: STRIPPED_ADMISSION_RECORD_TEXT }])
assert.deepEqual(all.message.content[2].content, all.message.content[0].content)
assert.notEqual(all.message.content[0].content[0], all.message.content[2].content[0])
assert.deepEqual(empty.content, [])
assert.deepEqual(removed.content, [ref('gone')])
console.log('PASS projection recreates all result arrays only after a removal, fills even prior empties, preserves other block references and leaves input untouched')
const untouched = user([empty, intact])
assert.equal(strip(untouched), untouched)
const nameless = user([result([ref(), ref(''), ref('present')], 'names')])
assert.equal(available(nameless, new Set(['present'])), nameless)
const selective = available(user([result([ref(), ref(''), ref('present'), ref('gone')], 'names')]), new Set(['present']))
assert.deepEqual(selective.message.content[0].content, [ref(), ref(''), ref('present')])
assert.deepEqual(available(row, new Set()).message.content[0].content, [{ type: 'text', text: '[Tool references removed - tools no longer available]' }])
const string = user('plain')
assert.equal(strip(string), string)
assert.equal(available(string, new Set()), string)
console.log('PASS selection keeps nameless and available references; untouched and string rows preserve identity')
