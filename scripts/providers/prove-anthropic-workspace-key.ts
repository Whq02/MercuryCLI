import assert from 'node:assert/strict'
import { accountsWorld, fixtureTurn, KEY, MODEL, WORKSPACE } from './anthropicAccountsFixture.ts'
const world = await accountsWorld()
try {
  world.requireWorkspace()
  await world.auth.saveApiKey(KEY, { workspaceId: WORKSPACE })
  world.auth.writeAnthropicPreferredSource('api-key')
  const answer = await fixtureTurn()
  assert.equal(answer.isApiErrorMessage, undefined, 'a stored organisation key must carry its workspace on the wire')
  const { getAuthHeaders } = await import('../../src/utils/http.ts')
  assert.equal(getAuthHeaders().headers['anthropic-workspace-id'], WORKSPACE)
  const { anthropicDoors, refreshAnthropicCatalogue } = await import('../../src/services/providers/anthropic/anthropicCatalogue.ts')
  assert.equal(anthropicDoors().find(door => door.door === 'api-key')?.headers['anthropic-workspace-id'], WORKSPACE)
  await refreshAnthropicCatalogue({ force: true, door: 'api-key' })
  const { getAnthropicClient } = await import('../../src/services/api/client.ts')
  const client = await getAnthropicClient({ maxRetries: 0 })
  await client.messages.countTokens({ model: MODEL, messages: [{ role: 'user', content: 'count' }] })
  assert.ok(world.requests.filter(row => row.key === KEY).every(row => row.workspace === WORKSPACE))
  const { storeAnthropicApiKeyLogin } = await import('../../src/services/providers/anthropic/anthropicLogin.ts')
  await world.auth.removeApiKey()
  const missing = await storeAnthropicApiKeyLogin(KEY)
  assert.equal(missing.stored, false)
  assert.equal(missing.needsWorkspace, true)
  assert.match(missing.receipt, /workspace ID/)
  assert.equal(world.auth.getAnthropicApiKey(), null)
  await world.auth.saveApiKey(KEY)
  const workspaceError = await fixtureTurn('missing workspace')
  assert.equal(workspaceError.isApiErrorMessage, true)
  const said = workspaceError.message.content.filter(block => block.type === 'text').map(block => block.text).join('')
  assert.match(said, /Open \/logins.*workspace ID/)
  assert.ok(!said.includes('\n'))
  const accepted = await storeAnthropicApiKeyLogin(KEY, { workspaceId: WORKSPACE })
  assert.equal(accepted.stored, true)
  process.env.ANTHROPIC_API_KEY = 'fixture-other-key'
  assert.equal(world.auth.getAnthropicApiKeyWorkspaceId('fixture-other-key'), undefined)
  delete process.env.ANTHROPIC_API_KEY
  await world.auth.saveApiKey('fixture-replacement')
  assert.equal(world.auth.getAnthropicApiKeyWorkspaceId('fixture-replacement'), undefined)
  console.log('PASS organisation key workspace on messages, counting and catalogue; paste asks before storage')
} finally { await world.close() }
