import { writeFileSync, appendFileSync } from 'node:fs'
import { join } from 'node:path'
import { cpuFixture, isolatedHome, readViewKit } from './readViewKit.js'

const home = isolatedHome(import.meta.filename)
const kit = await readViewKit(home)
const { read, check } = kit
const before = join(home, 'before.cpuprofile'), after = join(home, 'after.cpuprofile')
const cpu = cpuFixture()
writeFileSync(before, JSON.stringify(cpu))
writeFileSync(after, JSON.stringify({ ...cpu, endTime: 20000, timeDeltas: cpu.timeDeltas.map(n => n * 2) }))
const comparison = await read(`${after}#read?view=profile&compare=${before}`)
check('comparison names both sources', comparison.includes(`before: ${before}`) && comparison.includes(`after: ${after}`), comparison)
check('comparison names both denominators', comparison.includes('duration=10 ms') && comparison.includes('duration=20 ms') && comparison.includes('on-CPU=9 ms') && comparison.includes('on-CPU=18 ms'))
check('absolute work and normalized share are distinct', comparison.includes('self delta=8 ms') && comparison.includes('inclusive delta=8 ms') && comparison.includes('share delta=0 pp'), comparison)
check('comparison has no source anchor or evidence', !comparison.includes('(anchor:') && !kit.context.readFileState.has(before) && !kit.context.readFileState.has(after))
const broken = join(home, 'quality.cpuprofile')
writeFileSync(broken, JSON.stringify({ ...cpu, samples: [4, 99, 5, 6], timeDeltas: [3000, 2000, -1], nodes: cpu.nodes.map(n => n.id === 5 ? { ...n, children: [3, 123] } : n) }))
const quality = await read(broken)
check('sample/delta discrepancy is disclosed', quality.includes('Sample/delta lengths differ (4/3)'))
check('missing samples do not manufacture time', quality.includes('missing nodes') && quality.includes('weighted samples: 3 ms'))
check('cycle and missing-child diagnostics are explicit', quality.includes('Cycles were cut') && quality.includes('Missing child references'))
check('nonpositive deltas are disclosed', quality.includes('Nonpositive or invalid time deltas'))
const large = join(home, 'large.cpuprofile')
writeFileSync(large, '{"irrelevant":[')
for (let i = 0; i < 35; i++) appendFileSync(large, `${i ? ',' : ''}${'0,'.repeat(524287)}0`)
appendFileSync(large, `],${JSON.stringify(cpu).slice(1)}`)
const beforeRss = process.resourceUsage().maxRSS
let timerRan = false
const timer = setTimeout(() => { timerRan = true }, 5)
const largeResult = await read(large)
clearTimeout(timer)
const rssGrowth = (process.resourceUsage().maxRSS - beforeRss) / (process.versions.bun && process.platform === 'darwin' ? 1024 : 1)
console.log(`large profile peak-RSS growth: ${rssGrowth} KiB`)
check('large report does not retain its millions of irrelevant values', rssGrowth < 128 * 1024, String(rssGrowth))
check('over-32-MiB profile is fully summarized', largeResult.includes('self=8 ms'), largeResult.slice(0, 500))
check('large parser yields to the interactive process', timerRan)
const cancelled = new AbortController()
kit.context.abortController = cancelled
const stop = setTimeout(() => cancelled.abort(new Error('profile cancelled')), 5)
const cancelledResult = await read(large)
clearTimeout(stop)
check('cancellation is not empty success', cancelledResult.includes('profile cancelled') || cancelledResult.includes('AbortError'), cancelledResult.slice(0, 500))
kit.context.abortController = new AbortController()
const first = await read(`${after}#read?view=profile&limit=1`)
const next = /Read\(file_path: ("(?:[^"\\]|\\.)*")\) continues/.exec(first)
writeFileSync(after, JSON.stringify({ ...cpu, endTime: 15000 }))
check('continuation detects changed source', next !== null && (await read(JSON.parse(next[1]!))).includes('changed since the preceding page'))
const sampleA = join(home, 'a.sample.txt'), sampleB = join(home, 'b.sample.txt')
const sampleText = (interval: number) => `Analysis of sampling app every ${interval} millisecond\nCall graph:\n    5 Thread_1\n    + 5 _RNvNtCsabc_3app4work3run (in app)\n`
writeFileSync(sampleA, sampleText(1))
writeFileSync(sampleB, sampleText(2))
const symbol = await read(sampleA)
check('Rust v0 display keeps its original identity', symbol.includes('app::work::run') && symbol.includes('_RNvNtCsabc_3app4work3run') && symbol.includes('best-effort'))
check('different sampling rates are not compared as raw counts', (await read(`${sampleB}#read?view=profile&compare=${sampleA}`)).includes('Not comparable:'))
kit.deny('Read(before.cpuprofile)')
const denied = await read(`${after}#read?view=profile&compare=${before}`)
check('comparison cannot evade second-source deny', !denied.includes('self delta=') && /den/i.test(denied), denied)
kit.finish()
