import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { cpuFixture, isolatedHome, readViewKit } from './readViewKit.js'

const home = isolatedHome(import.meta.filename)
const kit = await readViewKit(home)
const { read, check, context } = kit
const file = join(home, 'work.cpuprofile')
const cpu = cpuFixture()
writeFileSync(file, JSON.stringify(cpu))
const summary = await read(file)
check('whole V8 read is a profile view', summary.includes('(target: profile') && summary.includes('format: V8'), summary)
check('measured milliseconds and denominator', summary.includes('weighted samples: 10 ms') && summary.includes('on-CPU estimate: 9 ms') && summary.includes('idle: 1 ms'), summary)
check('self and inclusive stay distinct', summary.includes('self=8 ms') && summary.includes('inclusive=8 ms') && summary.includes('self=0 ms') && summary.includes('inclusive=8 ms'), summary)
check('GC remains visible', summary.includes('(garbage collector)') && summary.includes('self=1 ms'), summary)
check('same-label siblings and recursion merge', (summary.match(/function="hot"/g) ?? []).length === 1, summary)
check('original source pointer is retained one-based', summary.includes('file="/project/work.ts"') && summary.includes('line=20'), summary)
check('view has no source anchor', !summary.includes('(anchor:'))
check('view grants no source coverage', !context.readFileState.has(file))
check('view offers exact raw escape', summary.includes(`${file}#read?view=raw`), summary)
check('explicit view follows the same route', (await read(`${file}#read?view=profile`)).includes('self=8 ms'))
const wrapped = join(home, 'wrapped.cpuprofile')
writeFileSync(wrapped, JSON.stringify({ profile: cpu }))
check('CDP wrapper is recognised', (await read(wrapped)).includes('self=8 ms'))
const fallback = join(home, 'fallback.cpuprofile')
writeFileSync(fallback, JSON.stringify({ ...cpu, samples: undefined, timeDeltas: undefined, nodes: cpu.nodes.map(n => ({ ...n, hitCount: n.id === 4 ? 4 : 0 })) }))
check('hit-count timing is called an approximation', (await read(fallback)).includes('hit-count approximation'))
const raw = await read(file, { offset: 1, limit: 1, lossless: true })
check('explicit source range keeps original numbered bytes', raw.includes(`1\t${JSON.stringify(cpu)}`) && raw.includes('(anchor:'))
check('raw read grants source coverage', context.readFileState.has(file))
check('partial raw offers exact summary discovery', raw.includes(`${file}#read?view=profile`))
const escaped = await read(`${file}#read?view=raw`, { offset: 1, limit: 1, lossless: true })
check('raw escape keeps original coordinates', escaped.includes(`1\t${JSON.stringify(cpu)}`) && escaped.includes('(anchor:'))
const named = join(home, 'ordinary.json')
writeFileSync(named, JSON.stringify(cpu))
check('profile-shaped differently named file stays raw', (await read(named)).includes('1\t') && !(await read(named)).includes('target: profile'))
const misnamed = join(home, 'invalid.cpuprofile')
writeFileSync(misnamed, '{"ordinary":true}\n')
check('misnamed V8 content stays raw', (await read(misnamed)).includes('1\t{"ordinary":true}'))
const sample = join(home, 'process.sample.txt')
writeFileSync(sample, 'Sampling process 123 for 10 milliseconds\nAnalysis of sampling process (pid 123) every 1 millisecond\nCall graph:\n    10 Thread_1   DispatchQueue_1: main\n    + 10 start (in app) [0x100]\n    +   8 _ZN3app4workE (in app) + 12 [0x120]\n    +   2 mach_msg_trap (in libsystem_kernel.dylib) + 8 [0x130]\n    10 Thread_2\n    + 10 __psynch_cvwait (in libsystem_kernel.dylib) + 8 [0x140]\nTotal number in stack (recursive counted multiple, when >=5):\n')
const sampled = await read(sample)
check('sample format works without recording', sampled.includes('format: macOS sample'), sampled)
check('active and waiting threads are explicit', sampled.includes('Thread_1') && sampled.includes('active') && sampled.includes('Thread_2') && sampled.includes('waiting'), sampled)
check('sample weighted self and wait denominator', sampled.includes('on-CPU estimate: 8 samples') && sampled.includes('idle: 12 samples'), sampled)
check('best-effort Rust name retains original symbol/module', sampled.includes('app::work') && sampled.includes('_ZN3app4workE') && sampled.includes('module="app"'), sampled)
const ordinary = join(home, 'ordinary.sample.txt')
writeFileSync(ordinary, 'not a sampling report\n')
check('sample name without sampling header stays raw', (await read(ordinary)).includes('1\tnot a sampling report'))
const page = await read(`${file}#read?view=profile&limit=1`)
const next = /Read\(file_path: ("(?:[^"\\]|\\.)*")\) continues/.exec(page)
check('view page has exact generated continuation', next !== null, page)
check('view continuation reaches remaining rows', next !== null && (await read(JSON.parse(next[1]!))).includes('target: profile'))
kit.deny('Read(work.cpuprofile)')
check('profile respects source deny', !(await read(`${file}#read?view=profile`)).includes('target: profile'))
kit.finish()
