#!/usr/bin/env bun
import { mkdirSync, symlinkSync } from 'node:fs'
import { join } from 'node:path'
import { checker, count, openWorld } from './instructionWorld.ts'

const world = openWorld('format-gemini')
const { check, section, close } = checker()
const contents = (path: string, body: string): string => `Contents of ${path} (project instructions, checked into the codebase):\n\n${body}`

try {
  section('§1 a project whose only guide is GEMINI.md')
  const p1 = world.project({ 'GEMINI.md': 'gemini-root-needle\n', 'src/a.ts': 'export const a = 1\n' })
  const d1 = world.drive(p1, { classify: [join(p1, 'GEMINI.md')] })
  check('the first request carries it in the form a shared guide has', d1.first === contents(join(p1, 'GEMINI.md'), 'gemini-root-needle'), d1.first)
  const e1 = d1.entries.find(e => e.path === join(p1, 'GEMINI.md'))
  check('the entry is shared, from the project walk, and names its format', e1?.family === 'shared' && e1.origin === 'project-walk' && e1.convention === 'gemini', JSON.stringify(e1))
  check('the folder counts as guided', JSON.stringify(d1.guides) === JSON.stringify([join(p1, 'GEMINI.md')]), JSON.stringify(d1.guides))
  check('the file classifies as an instruction file', d1.classified[join(p1, 'GEMINI.md')] === true)

  section('§2 the folder form beside it: both load, the root file first')
  const p2 = world.project({ 'GEMINI.md': 'gemini-root-needle\n', '.gemini/GEMINI.md': 'gemini-folder-needle\n' })
  const d2 = world.drive(p2, { classify: [join(p2, '.gemini/GEMINI.md'), join(p2, 'docs/GEMINI.md')] })
  check('both compose, each once', count(d2.first, 'gemini-root-needle') === 1 && count(d2.first, 'gemini-folder-needle') === 1, d2.paths.join(', '))
  check('the root file composes before the folder file', JSON.stringify(d2.paths) === JSON.stringify([join(p2, 'GEMINI.md'), join(p2, '.gemini/GEMINI.md')]), d2.paths.join(', '))
  check('the folder file classifies as an instruction file', d2.classified[join(p2, '.gemini/GEMINI.md')] === true)
  check('a GEMINI.md in any folder classifies as one (it attaches there)', d2.classified[join(p2, 'docs/GEMINI.md')] === true)
  const p2b = world.project({ '.gemini/GEMINI.md': 'gemini-folder-needle\n' })
  const d2b = world.drive(p2b)
  check('the folder form alone composes', d2b.first === contents(join(p2b, '.gemini/GEMINI.md'), 'gemini-folder-needle'), d2b.first)

  section('§3 an import in GEMINI.md is followed, inside the project')
  const p3 = world.project({ 'GEMINI.md': 'gemini-root-needle\n@./docs/style.md\n', 'docs/style.md': 'imported-style-needle\n' })
  const d3 = world.drive(p3)
  check('the imported file composes once', count(d3.first, 'imported-style-needle') === 1, d3.paths.join(', '))
  check('it rides the import chain of GEMINI.md', d3.entries.find(e => e.path === join(p3, 'docs/style.md'))?.parent === join(p3, 'GEMINI.md'), JSON.stringify(d3.entries))

  section('§4 MERCURY.md decides')
  const p4 = world.project({ 'MERCURY.md': 'native-needle\n', 'GEMINI.md': 'gemini-root-needle\n', '.gemini/GEMINI.md': 'gemini-folder-needle\n' })
  const d4 = world.drive(p4, { classify: [join(p4, 'GEMINI.md')] })
  check('MERCURY.md composes and neither Gemini file does', d4.first === contents(join(p4, 'MERCURY.md'), 'native-needle'), d4.first)
  check('that GEMINI.md is an ordinary file', d4.classified[join(p4, 'GEMINI.md')] === false)
  const p4b = world.project({ 'MERCURY.md': '@GEMINI.md\nnative-needle\n', 'GEMINI.md': 'gemini-root-needle\n' })
  const d4b = world.drive(p4b)
  check('an explicit import in MERCURY.md brings it in, once', count(d4b.first, 'gemini-root-needle') === 1 && d4b.first.includes('native-needle'), d4b.first)
  check('the imported file rides the native chain', d4b.entries.find(e => e.path === join(p4b, 'GEMINI.md'))?.parent === join(p4b, 'MERCURY.md'), JSON.stringify(d4b.entries))
  const p4c = world.project({ 'MERCURY.md': 'parent-native-needle\n', 'app/GEMINI.md': 'gemini-root-needle\n', 'app/a.ts': '\n' })
  const d4c = world.drive(join(p4c, 'app'), { trust: p4c })
  check('a MERCURY.md above the working directory decides too', d4c.first.includes('parent-native-needle') && !d4c.first.includes('gemini-root-needle'), d4c.first)
  const p4d = world.project({ 'MERCURY.local.md': 'local-needle\n', 'GEMINI.md': 'gemini-root-needle\n' })
  const d4d = world.drive(p4d)
  check('a MERCURY.local.md decides nothing: both compose, the personal layer last', d4d.first.includes('gemini-root-needle') && d4d.first.includes('local-needle') && d4d.paths.indexOf(join(p4d, 'GEMINI.md')) < d4d.paths.indexOf(join(p4d, 'MERCURY.local.md')), d4d.paths.join(', '))

  section('§5 the switches that exist: the native profile, the exclusion list, an untrusted folder')
  const d5 = world.drive(p2, { settings: { briefs: { profile: 'native' } }, classify: [join(p2, 'GEMINI.md')] })
  check('the native profile composes neither', d5.first === '', d5.first)
  check('under native the file is an ordinary file', d5.classified[join(p2, 'GEMINI.md')] === false)
  const d5b = world.drive(p2, { settings: { briefs: { exclude: ['**/GEMINI.md'] } } })
  check('an excluded GEMINI.md composes nothing', d5b.first === '', d5b.first)
  const d5c = world.drive(p2, { untrusted: true })
  check('a folder never trusted composes nothing headless', d5c.first === '' && d5c.paths.length === 0, d5c.paths.join(', '))

  section('§6 found from any folder of the repository, outermost first')
  const p6 = world.project({ 'GEMINI.md': 'outer-gemini-needle\n', 'packages/app/GEMINI.md': 'inner-gemini-needle\n', 'packages/app/a.ts': '\n' })
  const d6 = world.drive(join(p6, 'packages/app'), { trust: p6 })
  check('both compose', d6.first.includes('outer-gemini-needle') && d6.first.includes('inner-gemini-needle'), d6.paths.join(', '))
  check('the outer folder first', d6.paths.indexOf(join(p6, 'GEMINI.md')) < d6.paths.indexOf(join(p6, 'packages/app/GEMINI.md')) && d6.paths.indexOf(join(p6, 'GEMINI.md')) >= 0, d6.paths.join(', '))

  section('§7 a nested GEMINI.md attaches when a file beside it is touched')
  const p7 = world.project({ 'GEMINI.md': 'gemini-root-needle\n', 'sub/GEMINI.md': 'nested-gemini-needle\n', 'sub/file.ts': '\n', 'sub/other.ts': '\n', 'elsewhere/file.ts': '\n', 'mixed/MERCURY.md': 'nested-native-needle\n', 'mixed/GEMINI.md': 'nested-gemini-needle\n', 'mixed/file.ts': '\n' })
  const d7 = world.drive(p7, { touch: [join(p7, 'elsewhere/file.ts'), join(p7, 'sub/file.ts'), join(p7, 'sub/other.ts'), join(p7, 'mixed/file.ts')] })
  check('the first request does not carry the nested file', !d7.first.includes('nested-gemini-needle'), d7.first)
  check('a file elsewhere attaches nothing', d7.touched[0]!.attached.length === 0, JSON.stringify(d7.touched[0]))
  check('a file beside it attaches it, as a folder guide', d7.touched[1]!.attached.length === 1 && d7.touched[1]!.attached[0]!.told.includes(`Instruction file ${join(p7, 'sub/GEMINI.md')} (it governs its folder):\n\nnested-gemini-needle`), JSON.stringify(d7.touched[1]))
  check('a second file beside it attaches nothing more', d7.touched[2]!.attached.length === 0, JSON.stringify(d7.touched[2]))
  check('a nested folder holding a MERCURY.md attaches that alone', JSON.stringify(d7.touched[3]!.attached.map(a => a.path)) === JSON.stringify([join(p7, 'mixed/MERCURY.md')]), JSON.stringify(d7.touched[3]))
  const p7b = world.project({ 'MERCURY.md': 'native-needle\n', 'sub/GEMINI.md': 'nested-gemini-needle\n', 'sub/file.ts': '\n' })
  const d7b = world.drive(p7b, { touch: [join(p7b, 'sub/file.ts')] })
  check('under a MERCURY.md no nested GEMINI.md attaches', d7b.touched[0]!.attached.length === 0, JSON.stringify(d7b.touched[0]))

  section('§8 the walk stops below the home folder')
  const p8 = world.project({ '.gemini/GEMINI.md': 'personal-gemini-needle\n', 'GEMINI.md': 'home-root-gemini-needle\n', 'work/GEMINI.md': 'workspace-gemini-needle\n', 'work/proj/GEMINI.md': 'project-gemini-needle\n', 'work/proj/a.ts': '\n' })
  const d8 = world.drive(join(p8, 'work/proj'), { home: p8, trust: p8 })
  check('the project file and the workspace file above it compose', d8.first.includes('project-gemini-needle') && d8.first.includes('workspace-gemini-needle'), d8.paths.join(', '))
  check("the home folder's own files do not: they are the personal ones", !d8.first.includes('personal-gemini-needle') && !d8.first.includes('home-root-gemini-needle'), d8.paths.join(', '))
  const d8b = world.drive(join(p8, 'work/proj'), { trust: p8 })
  check('with the home elsewhere the same folders are plain parents and all four compose', ['personal-gemini-needle', 'home-root-gemini-needle', 'workspace-gemini-needle', 'project-gemini-needle'].every(needle => d8b.first.includes(needle)), d8b.paths.join(', '))
  const d8c = world.drive(p8, { home: p8 })
  check('started in the home folder itself, its root file is read and the tool folder there stays personal', d8c.first === contents(join(p8, 'GEMINI.md'), 'home-root-gemini-needle'), d8c.first)
  check('the guide list there names the root file alone', JSON.stringify(d8c.guides) === JSON.stringify([join(p8, 'GEMINI.md')]), JSON.stringify(d8c.guides))

  section('§9 beside the other shared guide: all load, identical text once')
  const p9 = world.project({ 'AGENTS.md': 'agents-needle\n', 'GEMINI.md': 'gemini-root-needle\n' })
  const d9 = world.drive(p9)
  check('AGENTS.md and GEMINI.md both compose, AGENTS.md first', JSON.stringify(d9.paths) === JSON.stringify([join(p9, 'AGENTS.md'), join(p9, 'GEMINI.md')]), d9.paths.join(', '))
  const p9b = world.project({ 'AGENTS.md': 'same-text-needle\n', 'GEMINI.md': 'same-text-needle\n' })
  const d9b = world.drive(p9b)
  check('two files of identical text compose once', count(d9b.first, 'same-text-needle') === 1, d9b.first)
  check('the dropped copy is reported as a duplicate', d9b.diagnostics.some(d => d.kind === 'duplicate-content' && d.path === join(p9b, 'GEMINI.md')), JSON.stringify(d9b.diagnostics))
  if (process.platform !== 'win32') {
    const p9c = world.project({ 'AGENTS.md': 'linked-text-needle\n' })
    mkdirSync(p9c, { recursive: true })
    symlinkSync('AGENTS.md', join(p9c, 'GEMINI.md'))
    const d9c = world.drive(p9c)
    check('a GEMINI.md that is a link to AGENTS.md composes its text once', count(d9c.first, 'linked-text-needle') === 1, d9c.first)
  }
} finally {
  world.close()
}
close('format-gemini')
