let generatedDeclaration: RegExp | null | undefined

function declaredGenerator(lines: string[]): string | undefined {
  if (generatedDeclaration === undefined) {
    try {
      generatedDeclaration = new RegExp(GENERATED_DECLARATION, 'i')
    } catch {
      generatedDeclaration = null
    }
  }
  if (generatedDeclaration === null) return undefined
  for (const line of lines) {
    const m = line.match(generatedDeclaration)
    if (!m) continue
    const script = m.slice(1).find(group => group !== undefined)
    if (script !== undefined) return script
  }
  return undefined
}

function cachedGeneratedPaths(rule: WardRule): Array<{ re: RegExp; row: GeneratedPath }> {
  let rows = compiledGeneratedPaths.get(rule)
  if (rows === undefined) {
    rows = []
    for (const row of rule.generatedPaths ?? []) {
      try {
        rows.push({ re: new RegExp(row.pattern), row })
      } catch {
        continue
      }
    }
    compiledGeneratedPaths.set(rule, rows)
  }
  return rows
}

function cachedLeadingMarker(rule: WardRule): RegExp | null {
  let re = compiledLeadingMarkers.get(rule)
  if (re === undefined) {
    try {
      re = rule.leadingMarker === undefined ? null : new RegExp(rule.leadingMarker, 'i')
    } catch {
      re = null
    }
    compiledLeadingMarkers.set(rule, re)
  }
  return re
}

function leadingMarkerHit(re: RegExp, head: string, work?: WardWork): { excerpt: string; line: number; generator?: string } | null {
  if (work) countWardWork(work, 'characters', Math.min(head.length, GENERATED_HEAD_CHARS))
  const lines = head.slice(0, GENERATED_HEAD_CHARS).split('\n', GENERATED_HEAD_LINES)
  for (let i = 0; i < lines.length; i++) {
    if (work) regexWork(work, lines[i]!)
    const m = lines[i]!.match(re)
    if (!m || m[0] === undefined) continue
    const generator = declaredGenerator(lines)
    return generator === undefined ? { excerpt: m[0].slice(0, 80), line: i + 1 } : { excerpt: m[0].slice(0, 80), line: i + 1, generator }
  }
  return null
}

function cachedPathRegex(
  map: WeakMap<WardRule, RegExp | null>,
  rule: WardRule,
  source: string,
): RegExp | null {
  let re = map.get(rule)
  if (re === undefined) {
    try {
      re = new RegExp(source)
    } catch {
      re = null
    }
    map.set(rule, re)
  }
  return re
}

function compile(rule: WardRule): RegExp[] {
  const cached = compiledPatterns.get(rule)
  if (cached !== undefined) return cached
  const out: RegExp[] = []
  for (const src of rule.patterns) {
    try {
      out.push(new RegExp(src, rule.flags ?? 'u'))
    } catch {
    }
  }
  compiledPatterns.set(rule, out)
  return out
}

let windowsRootPatterns: { home: string; patterns: RegExp[] } | undefined

const WINDOWS_MSYS_DRIVE_ROOT = '/[a-z]/?'

const WINDOWS_DRIVE = '(?:[a-z]:|%SystemDrive%|%HOMEDRIVE%|\\$\\{?env:(?:SystemDrive|HOMEDRIVE)\\}?)'
const WINDOWS_SYSTEM_FOLDER = '(?:Windows|Program Files(?: \\(x86\\))?|ProgramData)'
