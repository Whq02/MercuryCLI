const compiledPathPatterns = new WeakMap<WardRule, RegExp | null>()
const compiledAllowPathPatterns = new WeakMap<WardRule, RegExp | null>()
const compiledGeneratedPaths = new WeakMap<WardRule, Array<{ re: RegExp; row: GeneratedPath }>>()
const compiledLeadingMarkers = new WeakMap<WardRule, RegExp | null>()
const LEADING_SLASH = /^\//
const BLANK_RUN = /[ \t]+/g
