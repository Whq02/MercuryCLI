type QuicksilverMode = 'off' | 'mixed' | 'only'

export function quicksilverMode(): QuicksilverMode {
  const raw = flagEnv('MERCURY_HIP')
  if (raw === '0' || raw === 'false') return 'off'
  if (raw === '1' || raw === 'true') return 'only'
  return 'mixed'
}

